# Let's write an aggressive condenser that preserves meaning and hits < 3800 chars
def condense_strictly(text):
    # Let's inspect each hub and make it compact
    lines = text.split('\n')
    out = []
    for l in lines:
        s = l.strip()
        if not s:
            continue
        # remove trailing periods
        if s.endswith('.'):
            s = s[:-1]
        out.append(s)
    joined = '\n'.join(out)
    return joined

